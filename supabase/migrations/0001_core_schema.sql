create or replace function public.firewatch_runtime_config()
returns jsonb
language sql stable security definer
set search_path=public,extensions,pg_temp
as $$
with a as (
  select extensions.st_extent(geom) box
  from public.monitoring_areas
  where enabled
), c as (
  select * from public.project_config where id=true
)
select jsonb_build_object(
  'project_name',c.project_name,
  'timezone',c.timezone,
  'poll_interval_minutes',c.poll_interval_minutes,
  'event_match_hours',c.event_match_hours,
  'bootstrap_fresh_hours',c.bootstrap_fresh_hours,
  'telegram_enabled',c.telegram_enabled,
  'dashboard_enabled',c.dashboard_enabled,
  'bbox',case when a.box is null then null else jsonb_build_array(
    extensions.st_xmin(a.box),extensions.st_ymin(a.box),
    extensions.st_xmax(a.box),extensions.st_ymax(a.box)
  ) end,
  'sources',coalesce((
    select jsonb_agg(jsonb_build_object(
      'source_id',source_id,'resolution_m',resolution_m,
      'match_radius_m',match_radius_m,'display_name',display_name
    ) order by sort_order)
    from public.firms_sources where enabled
  ),'[]'::jsonb)
)
from a,c;
$$;

create or replace function public.firewatch_point_in_aoi(p_latitude double precision,p_longitude double precision)
returns boolean
language sql stable security definer
set search_path=public,extensions,pg_temp
as $$
select exists(
  select 1 from public.monitoring_areas a
  where a.enabled and extensions.st_covers(
    a.geom,extensions.st_setsrid(extensions.st_makepoint(p_longitude,p_latitude),4326)
  )
);
$$;

create or replace function public.lookup_region_id(p_latitude double precision,p_longitude double precision)
returns bigint
language sql stable security definer
set search_path=public,extensions,pg_temp
as $$
select r.id from public.regions r
where r.enabled and extensions.st_covers(
  r.geom,extensions.st_setsrid(extensions.st_makepoint(p_longitude,p_latitude),4326)
)
order by r.id limit 1;
$$;

create or replace function public.firewatch_set_geography(
  p_aoi jsonb,
  p_regions jsonb default null
)
returns jsonb
language plpgsql security definer
set search_path=public,extensions,pg_temp
as $$
declare
  f jsonb;
  g extensions.geometry;
  n_aoi integer:=0;
  n_regions integer:=0;
begin
  if p_aoi is null or p_aoi->>'type'<>'FeatureCollection' then
    raise exception 'AOI must be a GeoJSON FeatureCollection';
  end if;

  delete from public.monitoring_areas where id is not null;

  for f in select value from jsonb_array_elements(p_aoi->'features') loop
    g:=extensions.st_setsrid(extensions.st_geomfromgeojson((f->'geometry')::text),4326);
    if geometrytype(g)='POLYGON' then g:=extensions.st_multi(g); end if;
    if geometrytype(g)<>'MULTIPOLYGON' then raise exception 'AOI geometry must be Polygon or MultiPolygon'; end if;
    if not extensions.st_isvalid(g) then raise exception 'Invalid AOI geometry'; end if;
    insert into public.monitoring_areas(code,name,geom)
    values(
      nullif(f->'properties'->>'code',''),
      coalesce(nullif(f->'properties'->>'name',''),'Monitoring area'),
      g
    );
    n_aoi:=n_aoi+1;
  end loop;

  delete from public.regions where id is not null;
  if p_regions is not null then
    if p_regions->>'type'<>'FeatureCollection' then
      raise exception 'Regions must be a GeoJSON FeatureCollection';
    end if;
    for f in select value from jsonb_array_elements(p_regions->'features') loop
      g:=extensions.st_setsrid(extensions.st_geomfromgeojson((f->'geometry')::text),4326);
      if geometrytype(g)='POLYGON' then g:=extensions.st_multi(g); end if;
      if geometrytype(g)<>'MULTIPOLYGON' then raise exception 'Region geometry must be Polygon or MultiPolygon'; end if;
      if not extensions.st_isvalid(g) then raise exception 'Invalid region geometry'; end if;
      insert into public.regions(code,name,source,source_id,geom)
      values(
        nullif(coalesce(f->'properties'->>'code',f->'properties'->>'id'),''),
        coalesce(f->'properties'->>'name',f->'properties'->>'NAME_1',f->'properties'->>'shapeName','Region'),
        coalesce(f->'properties'->>'source','user'),
        nullif(f->'properties'->>'source_id',''),
        g
      );
      n_regions:=n_regions+1;
    end loop;
  end if;

  insert into public.system_state(key,value,updated_at)
  values('geography',jsonb_build_object(
    'configured',true,'aoi_features',n_aoi,'region_features',n_regions,'configured_at',now()
  ),now())
  on conflict(key) do update set value=excluded.value,updated_at=excluded.updated_at;

  return jsonb_build_object('ok',true,'aoi_features',n_aoi,'region_features',n_regions,'runtime',public.firewatch_runtime_config());
end;
$$;

create or replace function public.ingest_firms_detection(
  p_source text,p_satellite text,p_instrument text,p_acq_datetime timestamptz,
  p_latitude double precision,p_longitude double precision,
  p_scan double precision default null,p_track double precision default null,
  p_confidence text default null,p_frp double precision default null,
  p_daynight text default null,p_raw jsonb default '{}'::jsonb,
  p_match_radius_m integer default 750,p_match_window_hours integer default 24,
  p_resolution_m integer default null
)
returns jsonb
language plpgsql security definer
set search_path=public,extensions,pg_temp
as $$
declare
  v_point extensions.geography(Point,4326);
  v_region_id bigint;
  v_hash text;
  v_detection_id uuid;
  v_event_id uuid;
  v_existing_event uuid;
  v_new boolean:=false;
begin
  if not public.firewatch_point_in_aoi(p_latitude,p_longitude) then
    return jsonb_build_object('inserted',false,'duplicate',false,'outside_aoi',true,'is_new_event',false,'should_notify',false);
  end if;

  v_point:=extensions.st_setsrid(extensions.st_makepoint(p_longitude,p_latitude),4326)::extensions.geography;
  v_region_id:=public.lookup_region_id(p_latitude,p_longitude);
  v_hash:=encode(extensions.digest(concat_ws('|',
    coalesce(p_source,''),coalesce(p_satellite,''),coalesce(p_instrument,''),
    to_char(p_acq_datetime at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US'),
    to_char(round(p_latitude::numeric,6),'FM999990.000000'),
    to_char(round(p_longitude::numeric,6),'FM999990.000000')
  ),'sha256'),'hex');

  insert into public.detections(
    detection_hash,region_id,source,satellite,instrument,acq_datetime,
    latitude,longitude,location,scan,track,confidence,frp,daynight,resolution_m,raw
  ) values(
    v_hash,v_region_id,p_source,p_satellite,p_instrument,p_acq_datetime,
    p_latitude,p_longitude,v_point,p_scan,p_track,p_confidence,p_frp,p_daynight,p_resolution_m,coalesce(p_raw,'{}'::jsonb)
  )
  on conflict(detection_hash) do nothing returning id into v_detection_id;

  if v_detection_id is null then
    select id,event_id into v_detection_id,v_existing_event from public.detections where detection_hash=v_hash;
    return jsonb_build_object('inserted',false,'duplicate',true,'outside_aoi',false,'detection_id',v_detection_id,'event_id',v_existing_event,'is_new_event',false,'should_notify',false);
  end if;

  select e.id into v_event_id
  from public.fire_events e
  where e.status in('active','inactive')
    and (v_region_id is null or e.region_id is null or e.region_id=v_region_id)
    and p_acq_datetime between e.first_seen-make_interval(hours=>p_match_window_hours)
                           and e.last_seen+make_interval(hours=>p_match_window_hours)
    and extensions.st_dwithin(e.last_location,v_point,p_match_radius_m)
  order by extensions.st_distance(e.last_location,v_point),e.last_seen desc
  limit 1 for update;

  if v_event_id is null then
    insert into public.fire_events(
      region_id,status,lifecycle_status,first_seen,last_seen,
      first_latitude,first_longitude,last_latitude,last_longitude,
      first_location,last_location,best_latitude,best_longitude,best_location,
      best_location_resolution_m,observation_count,multisource_count,multisource_sources,
      match_radius_m,notification_required
    ) values(
      v_region_id,'active','active',p_acq_datetime,p_acq_datetime,
      p_latitude,p_longitude,p_latitude,p_longitude,
      v_point,v_point,p_latitude,p_longitude,v_point,p_resolution_m,
      1,1,array[coalesce(p_satellite,p_source)],p_match_radius_m,true
    ) returning id into v_event_id;
    v_new:=true;
  else
    update public.fire_events e set
      region_id=coalesce(e.region_id,v_region_id),
      status='active',lifecycle_status='active',
      first_seen=least(e.first_seen,p_acq_datetime),
      last_seen=greatest(e.last_seen,p_acq_datetime),
      last_latitude=case when p_acq_datetime>=e.last_seen then p_latitude else e.last_latitude end,
      last_longitude=case when p_acq_datetime>=e.last_seen then p_longitude else e.last_longitude end,
      last_location=case when p_acq_datetime>=e.last_seen then v_point else e.last_location end,
      best_latitude=case when e.best_location_resolution_m is null or coalesce(p_resolution_m,999999)<e.best_location_resolution_m then p_latitude else e.best_latitude end,
      best_longitude=case when e.best_location_resolution_m is null or coalesce(p_resolution_m,999999)<e.best_location_resolution_m then p_longitude else e.best_longitude end,
      best_location=case when e.best_location_resolution_m is null or coalesce(p_resolution_m,999999)<e.best_location_resolution_m then v_point else e.best_location end,
      best_location_resolution_m=least(coalesce(e.best_location_resolution_m,999999),coalesce(p_resolution_m,999999)),
      observation_count=e.observation_count+1,
      updated_at=now()
    where e.id=v_event_id;
  end if;

  update public.detections set event_id=v_event_id where id=v_detection_id;

  update public.fire_events e set
    multisource_sources=x.sources,
    multisource_count=cardinality(x.sources)
  from (
    select array_agg(distinct coalesce(nullif(satellite,''),source) order by coalesce(nullif(satellite,''),source)) sources
    from public.detections where event_id=v_event_id
  ) x
  where e.id=v_event_id;

  return jsonb_build_object(
    'inserted',true,'duplicate',false,'outside_aoi',false,
    'detection_id',v_detection_id,'event_id',v_event_id,'region_id',v_region_id,
    'is_new_event',v_new,'should_notify',v_new
  );
end;
$$;

create or replace function public.ingest_firms_batch(
  p_records jsonb,p_match_window_hours integer default 24
)
returns jsonb
language plpgsql security definer
set search_path=public,extensions,pg_temp
as $$
declare
  r jsonb; res jsonb;
  inserted_count integer:=0; duplicate_count integer:=0; outside_count integer:=0; new_event_count integer:=0;
begin
  if jsonb_typeof(p_records)<>'array' then raise exception 'p_records must be JSON array'; end if;
  for r in select value from jsonb_array_elements(p_records) loop
    res:=public.ingest_firms_detection(
      r->>'source',r->>'satellite',coalesce(r->>'instrument','VIIRS'),
      (r->>'acq_datetime')::timestamptz,(r->>'latitude')::double precision,(r->>'longitude')::double precision,
      nullif(r->>'scan','')::double precision,nullif(r->>'track','')::double precision,
      nullif(r->>'confidence',''),nullif(r->>'frp','')::double precision,nullif(r->>'daynight',''),
      r,coalesce((r->>'match_radius_m')::integer,750),p_match_window_hours,
      nullif(r->>'resolution_m','')::integer
    );
    if coalesce((res->>'inserted')::boolean,false) then inserted_count:=inserted_count+1; end if;
    if coalesce((res->>'duplicate')::boolean,false) then duplicate_count:=duplicate_count+1; end if;
    if coalesce((res->>'outside_aoi')::boolean,false) then outside_count:=outside_count+1; end if;
    if coalesce((res->>'is_new_event')::boolean,false) then new_event_count:=new_event_count+1; end if;
  end loop;
  return jsonb_build_object(
    'inserted',inserted_count,'duplicates',duplicate_count,
    'outside_aoi',outside_count,'new_events',new_event_count
  );
end;
$$;

create or replace function public.verify_firewatch_cron_secret(p_secret text)
returns boolean
language sql stable security definer
set search_path=public,vault,pg_temp
as $$
select coalesce((
  select p_secret=decrypted_secret from vault.decrypted_secrets
  where name='firewatch_cron_secret' limit 1
),false);
$$;

