create extension if not exists postgis with schema extensions;
create extension if not exists pgcrypto with schema extensions;

create table public.project_config (
  id boolean primary key default true check (id),
  project_name text not null default 'FIRMSGeoTools',
  timezone text not null default 'UTC',
  poll_interval_minutes integer not null default 15 check (poll_interval_minutes between 5 and 60),
  event_match_hours integer not null default 24 check (event_match_hours between 1 and 168),
  bootstrap_fresh_hours integer not null default 3 check (bootstrap_fresh_hours between 0 and 24),
  telegram_enabled boolean not null default true,
  dashboard_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.project_config(id) values(true) on conflict do nothing;

create table public.monitoring_areas (
  id bigint generated by default as identity primary key,
  code text unique,
  name text not null,
  geom extensions.geometry(MultiPolygon,4326) not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.regions (
  id bigint generated by default as identity primary key,
  code text unique,
  name text not null,
  source text,
  source_id text,
  geom extensions.geometry(MultiPolygon,4326) not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.fire_events (
  id uuid primary key default gen_random_uuid(),
  region_id bigint references public.regions(id) on delete set null,
  status text not null default 'active' check (status in ('active','inactive','closed')),
  lifecycle_status text not null default 'active' check (lifecycle_status in ('active','closed')),
  first_seen timestamptz not null,
  last_seen timestamptz not null,
  first_latitude double precision not null check(first_latitude between -90 and 90),
  first_longitude double precision not null check(first_longitude between -180 and 180),
  last_latitude double precision not null check(last_latitude between -90 and 90),
  last_longitude double precision not null check(last_longitude between -180 and 180),
  first_location extensions.geography(Point,4326) not null,
  last_location extensions.geography(Point,4326) not null,
  best_latitude double precision,
  best_longitude double precision,
  best_location extensions.geography(Point,4326),
  best_location_resolution_m integer,
  observation_count integer not null default 1 check(observation_count>=1),
  multisource_count integer not null default 1,
  multisource_sources text[] not null default '{}',
  match_radius_m integer not null default 750 check(match_radius_m>0),
  notification_required boolean not null default true,
  telegram_sent boolean not null default false,
  telegram_sent_at timestamptz,
  telegram_message_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check(last_seen>=first_seen)
);

create table public.detections (
  id uuid primary key default gen_random_uuid(),
  detection_hash text not null unique,
  event_id uuid references public.fire_events(id) on delete set null,
  region_id bigint references public.regions(id) on delete set null,
  source text not null,
  satellite text,
  instrument text not null,
  acq_datetime timestamptz not null,
  latitude double precision not null check(latitude between -90 and 90),
  longitude double precision not null check(longitude between -180 and 180),
  location extensions.geography(Point,4326) not null,
  scan double precision,
  track double precision,
  confidence text,
  frp double precision,
  daynight text check(daynight is null or daynight in ('D','N')),
  resolution_m integer,
  raw jsonb,
  received_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table public.system_state (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

